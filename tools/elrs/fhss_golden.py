#!/usr/bin/env python3
"""Generate FHSS golden vectors by compiling the real ExpressLRS FHSS code natively.

Reads src/lib/FHSS/{random.cpp,random.h,FHSS.cpp} from a git tag of an ELRS
checkout; nothing from ELRS is written into this repository, only derived numbers.
"""
import argparse
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

PHRASES = [('test', b'test'), ('chb', b'correct horse battery')]
OTA_VERSION_ID = 3
SEQ_LEN = 240
NCH = 80
SYNC_CH = 41

HARNESS = r'''
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#define DBG(...)
#define DBGCR
#define DBGLN(...)
volatile uint8_t FHSSptr;
static inline uint16_t FHSSgetSequenceCount() { return 240; }
#include "random.h"
#include "build_fn.inc"
int main(int argc, char **argv)
{
    uint8_t seq[256];
    FHSSrandomiseFHSSsequenceBuild((uint32_t)strtoul(argv[1], 0, 0), 80, 41, seq);
    for (int i = 0; i < 240; i++) printf("%u\n", seq[i]);
    return 0;
}
'''


def git_show(elrs, tag, path):
    return subprocess.run(['git', '-C', str(elrs), 'show', f'{tag}:{path}'],
                          check=True, capture_output=True, text=True).stdout


def extract_function(src, signature):
    start = src.index('\n' + signature) + 1
    brace = src.index('{', start)
    depth = 0
    for i in range(brace, len(src)):
        if src[i] == '{':
            depth += 1
        elif src[i] == '}':
            depth -= 1
            if depth == 0:
                return src[start:i + 1] + '\n'
    raise ValueError('unbalanced braces')


def uid_for(phrase):
    return hashlib.md5(b'-DMY_BINDING_PHRASE="' + phrase + b'"').digest()[:6]


def seed_for(uid):
    return ((uid[2] << 24) + (uid[3] << 16) + (uid[4] << 8) + (uid[5] ^ OTA_VERSION_ID)) & 0xFFFFFFFF


def fmt_bytes(values, per_line):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(f'{v}' for v in values[i:i + per_line]) + ',')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--elrs', required=True)
    ap.add_argument('--tag', required=True)
    ap.add_argument('--output', required=True)
    args = ap.parse_args()
    elrs = Path(args.elrs)
    commit = subprocess.run(['git', '-C', str(elrs), 'rev-parse', f'{args.tag}^{{commit}}'],
                            check=True, capture_output=True, text=True).stdout.strip()

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for name in ('random.cpp', 'random.h'):
            (tmp / name).write_text(git_show(elrs, args.tag, f'src/lib/FHSS/{name}'))
        fhss = git_show(elrs, args.tag, 'src/lib/FHSS/FHSS.cpp')
        (tmp / 'build_fn.inc').write_text(extract_function(
            fhss, 'void FHSSrandomiseFHSSsequenceBuild('))
        (tmp / 'harness.cpp').write_text(HARNESS)
        exe = tmp / 'harness'
        subprocess.run(['c++', '-std=c++17', '-O1', '-I', str(tmp), str(tmp / 'harness.cpp'),
                        str(tmp / 'random.cpp'), '-o', str(exe)], check=True)

        out = [f'/* Generated by tools/elrs/fhss_golden.py from ExpressLRS {args.tag} ({commit}). Do not edit. */',
               '#pragma once', '#include <stdint.h>', '']
        for n, phrase in PHRASES:
            uid = uid_for(phrase)
            seed = seed_for(uid)
            res = subprocess.run([str(exe), str(seed)], check=True, capture_output=True, text=True)
            seq = [int(x) for x in res.stdout.split()]
            assert len(seq) == SEQ_LEN and seq[0] == SYNC_CH
            out.append(f'static const uint8_t golden_uid_{n}[6] = {{' +
                       ', '.join(f'0x{b:02x}' for b in uid) + '};')
            out.append(f'static const uint32_t golden_seed_{n} = 0x{seed:08x}u;')
            out.append(f'static const uint8_t golden_seq_{n}[{SEQ_LEN}] = {{')
            out.append(fmt_bytes(seq, 12))
            out.append('};')
            out.append('')
    Path(args.output).write_text('\n'.join(out))


if __name__ == '__main__':
    sys.exit(main())
